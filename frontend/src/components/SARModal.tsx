import React, { useState } from 'react';
import { X, FileText, Download, Copy, Check, ShieldAlert, AlertTriangle } from 'lucide-react';
import { SARReport } from '../types';

interface SARModalProps {
  sar: SARReport | null;
  onClose: () => void;
}

export const SARModal: React.FC<SARModalProps> = ({ sar, onClose }) => {
  const [copied, setCopied] = useState(false);

  if (!sar) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(sar.narrative_summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const content = `# SUSPICIOUS ACTIVITY REPORT (SAR)
Filing ID: ${sar.sar_id}
Filing Date: ${sar.filing_date}
Filing Institution: ${sar.filing_institution}
Threat Priority: ${sar.threat_level} (${sar.risk_score.toFixed(2)})
Primary Typology: ${sar.primary_typology}
Total Suspicious Volume: $${sar.total_volume_usd.toLocaleString()} USD
Counterparties: ${sar.suspect_accounts.join(', ')}

======================================================================
1. REGULATORY NARRATIVE
======================================================================
${sar.narrative_summary}

======================================================================
2. CHRONOLOGICAL MONEY TRAIL
======================================================================
${sar.chronological_trail.map((s) => `[Step ${s.step_number}] ${s.formatted_time} | ${s.description}`).join('\n')}

======================================================================
3. RED FLAG INDICATORS
======================================================================
${sar.red_flag_indicators.map((rf) => `- ${rf}`).join('\n')}

======================================================================
4. RECOMMENDED REMEDIATION
======================================================================
${sar.recommended_action}
`;

    const blob = new Blob([content], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${sar.sar_id}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 bg-slate-950/80 backdrop-blur-sm z-50 flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl max-w-4xl w-full max-h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="p-5 border-b border-slate-800 flex items-center justify-between bg-slate-950/50">
          <div className="flex items-center space-x-3">
            <div className="w-9 h-9 rounded-lg bg-rose-500/10 border border-rose-500/20 flex items-center justify-center">
              <FileText className="w-5 h-5 text-rose-400" />
            </div>
            <div>
              <div className="flex items-center space-x-2">
                <h3 className="text-base font-bold text-slate-100">
                  Suspicious Activity Report (FinCEN Form 111 Standard)
                </h3>
                <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-slate-800 text-slate-300">
                  {sar.sar_id}
                </span>
              </div>
              <p className="text-xs text-slate-400">
                Generated by GraphSleuth Explainable AI Compliance Engine • {sar.filing_date}
              </p>
            </div>
          </div>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleCopy}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied!' : 'Copy Narrative'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center space-x-1.5 px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-medium transition shadow"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Export .MD</span>
            </button>
            <button
              onClick={onClose}
              className="w-8 h-8 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-400 hover:text-slate-200 flex items-center justify-center transition"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>

        {/* Content Body */}
        <div className="flex-1 overflow-y-auto p-6 space-y-6">
          {/* Key Facts Strip */}
          <div className="grid grid-cols-2 md:grid-cols-4 gap-3 bg-slate-950/70 p-4 rounded-xl border border-slate-800/80 font-mono text-xs">
            <div>
              <span className="text-slate-500 text-[10px] uppercase">Threat Level</span>
              <div className="font-bold text-rose-400 text-sm mt-0.5">
                {sar.threat_level} ({(sar.risk_score * 100).toFixed(0)}%)
              </div>
            </div>
            <div>
              <span className="text-slate-500 text-[10px] uppercase">Laundering Typology</span>
              <div className="font-bold text-amber-400 text-sm mt-0.5">{sar.primary_typology}</div>
            </div>
            <div>
              <span className="text-slate-500 text-[10px] uppercase">Total Money Trail</span>
              <div className="font-bold text-slate-200 text-sm mt-0.5">
                ${sar.total_volume_usd.toLocaleString(undefined, { maximumFractionDigits: 0 })} USD
              </div>
            </div>
            <div>
              <span className="text-slate-500 text-[10px] uppercase">Entities / Time Span</span>
              <div className="font-bold text-slate-200 text-sm mt-0.5">
                {sar.suspect_accounts.length} entities • {sar.time_span_hours.toFixed(1)}h
              </div>
            </div>
          </div>

          {/* Narrative Summary */}
          <div className="space-y-2">
            <h4 className="text-xs font-mono uppercase text-slate-400 font-semibold flex items-center space-x-1.5">
              <ShieldAlert className="w-4 h-4 text-cyan-400" />
              <span>Plain-Language Investigative Narrative</span>
            </h4>
            <div className="bg-slate-950/90 border border-slate-800 rounded-xl p-4 text-slate-300 text-xs leading-relaxed font-mono whitespace-pre-wrap">
              {sar.narrative_summary}
            </div>
          </div>

          {/* Chronological Flow Table */}
          {sar.chronological_trail.length > 0 && (
            <div className="space-y-2">
              <h4 className="text-xs font-mono uppercase text-slate-400 font-semibold">
                Chronological Transaction Sequence ({sar.chronological_trail.length} steps)
              </h4>
              <div className="border border-slate-800 rounded-xl overflow-hidden">
                <table className="w-full text-left text-xs font-mono">
                  <thead className="bg-slate-950 text-slate-400 border-b border-slate-800">
                    <tr>
                      <th className="px-4 py-2">Step</th>
                      <th className="px-4 py-2">Timestamp</th>
                      <th className="px-4 py-2">Source</th>
                      <th className="px-4 py-2">Target</th>
                      <th className="px-4 py-2 text-right">Amount</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60 text-slate-300">
                    {sar.chronological_trail.map((step) => (
                      <tr key={step.step_number} className="hover:bg-slate-800/30">
                        <td className="px-4 py-2 text-cyan-400">#{step.step_number}</td>
                        <td className="px-4 py-2 text-slate-400">{step.formatted_time}</td>
                        <td className="px-4 py-2">{step.source_account}</td>
                        <td className="px-4 py-2">{step.target_account}</td>
                        <td className="px-4 py-2 text-right font-semibold text-slate-100">
                          ${step.amount.toLocaleString(undefined, { minimumFractionDigits: 2 })}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          )}

          {/* Red Flags & Regulatory Action */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="bg-slate-950/60 border border-slate-800 rounded-xl p-4 space-y-2">
              <h5 className="text-xs font-semibold text-rose-400 flex items-center space-x-1.5">
                <AlertTriangle className="w-4 h-4" />
                <span>Statutory Red Flags Cited</span>
              </h5>
              <ul className="list-disc list-inside text-xs text-slate-400 space-y-1">
                {sar.red_flag_indicators.map((rf, idx) => (
                  <li key={idx}>{rf}</li>
                ))}
              </ul>
            </div>

            <div className="bg-slate-950/60 border border-slate-800 rounded-xl p-4 space-y-2">
              <h5 className="text-xs font-semibold text-indigo-400 flex items-center space-x-1.5">
                <ShieldAlert className="w-4 h-4" />
                <span>Enforcement Recommendation</span>
              </h5>
              <p className="text-xs text-slate-300 leading-relaxed">{sar.recommended_action}</p>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

